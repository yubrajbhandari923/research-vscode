"""Project-local CLI: `.research/bin/research`.

Copies the running `research` + `research_cli` packages into `.research/bin/lib/` and writes small launchers next
to them, so any agent or shell in the project can run `.research/bin/research …` without `pip install` or a
PATH change (e.g. Claude Code's Bash tool, which does not see VS Code's terminal environment).

The copy is per machine (the launcher records this machine's Python), so `bin/` is gitignored. It is refreshed
whenever the source code differs, by `research init`, `research bin install` and the VS Code extension.
"""
from __future__ import annotations

import hashlib
import os
import shutil
import sys
from typing import Any, Dict, List, Optional, Tuple

from .util import ResearchError

PACKAGES = ("research", "research_cli")
SKIP_DIRS = {"__pycache__"}
GITIGNORE_LINE = "bin/"


def _ledger(root: str) -> str:
    from . import workspace
    loc = workspace.locate(root)
    return loc.ledger_root if loc else root


def bin_dir(root: str) -> str:
    return os.path.join(_ledger(root), ".research", "bin")


def launcher(root: str) -> str:
    return os.path.join(bin_dir(root), "research.cmd" if os.name == "nt" else "research")


def _sources() -> List[Tuple[str, str]]:
    """(package name, source dir) for the code that is running right now."""
    import research
    out = [("research", os.path.dirname(os.path.abspath(research.__file__)))]
    try:
        import research_cli
        out.append(("research_cli", os.path.dirname(os.path.abspath(research_cli.__file__))))
    except ImportError:
        pass
    return out


def _walk(src: str):
    for d, dirs, files in os.walk(src):
        dirs[:] = sorted(x for x in dirs if x not in SKIP_DIRS)
        for f in sorted(files):
            if not f.endswith((".pyc", ".pyo")):
                yield os.path.join(d, f)


def _stamp(sources: List[Tuple[str, str]], python: str) -> str:
    h = hashlib.sha256(python.encode())
    for name, src in sources:
        for f in _walk(src):
            st = os.stat(f)
            h.update(f"{name}/{os.path.relpath(f, src)}:{st.st_size}:{int(st.st_mtime)}".encode())
    from . import __version__
    return f"{__version__}:{h.hexdigest()[:16]}"


def _sh(s: str) -> str:
    return "'" + s.replace("'", "'\\''") + "'"


def _posix_launcher(python: str) -> str:
    return f"""#!/bin/sh
# Research OS CLI for this project — generated by `research bin install` / the Research Panel extension.
# Runs the copy of the CLI in .research/bin/lib: no pip install or PATH change needed. Safe to delete;
# it is recreated automatically. Override the interpreter with RESEARCH_PYTHON=/path/to/python3.
SELF="$0"
while [ -L "$SELF" ]; do   # run through a symlink (for example ./research in the main checkout)
  LINK=$(readlink "$SELF")
  case "$LINK" in /*) SELF="$LINK" ;; *) SELF="$(dirname -- "$SELF")/$LINK" ;; esac
done
HERE=$(CDPATH= cd -- "$(dirname -- "$SELF")" && pwd)
PY="${{RESEARCH_PYTHON:-}}"
if [ -z "$PY" ]; then
  for c in {_sh(python)} python3 python; do
    if command -v "$c" >/dev/null 2>&1; then PY="$c"; break; fi
  done
fi
if [ -z "$PY" ]; then echo "research: no Python 3 found (set RESEARCH_PYTHON)" >&2; exit 127; fi
PYTHONPATH="$HERE/lib${{PYTHONPATH:+:$PYTHONPATH}}" exec "$PY" -m research_cli "$@"
"""


def _windows_launcher(python: str) -> str:
    return (
        "@echo off\r\n"
        "rem Research OS CLI for this project - generated by `research bin install` / the Research Panel extension.\r\n"
        "setlocal\r\n"
        "set \"PY=%RESEARCH_PYTHON%\"\r\n"
        f"if \"%PY%\"==\"\" if exist \"{python}\" set \"PY={python}\"\r\n"
        "if \"%PY%\"==\"\" set \"PY=python\"\r\n"
        "set \"PYTHONPATH=%~dp0lib;%PYTHONPATH%\"\r\n"
        "\"%PY%\" -m research_cli %*\r\n"
    )


def _ensure_gitignored(root: str) -> None:
    gi = os.path.join(_ledger(root), ".research", ".gitignore")
    try:
        text = open(gi, encoding="utf-8").read() if os.path.exists(gi) else ""
    except OSError:
        return
    if any(line.strip() in (GITIGNORE_LINE, "/bin/", "bin") for line in text.splitlines()):
        return
    with open(gi, "a", encoding="utf-8") as f:
        f.write(("" if not text or text.endswith("\n") else "\n")
                + "# project-local CLI (per machine, recreated automatically)\n" + GITIGNORE_LINE + "\n")


def status(root: str) -> Dict[str, Any]:
    path = launcher(root)
    stamp_file = os.path.join(bin_dir(root), "lib", ".stamp")
    stamp = open(stamp_file).read().strip() if os.path.exists(stamp_file) else None
    return {"path": path, "exists": os.path.exists(path), "stamp": stamp}


def install(root: str, python: Optional[str] = None, force: bool = False) -> Dict[str, Any]:
    """Create or refresh `.research/bin/`. Cheap when nothing changed (compares a stamp, copies nothing)."""
    python = python or sys.executable or "python3"
    sources = _sources()
    # `.research/bin/research` runs the copy inside .research/bin/lib, so asking *it* to reinstall would
    # copy that copy onto itself: the stamp changes and nothing is actually upgraded. Refuse instead of
    # silently doing nothing, and say which command does work.
    lib = os.path.realpath(os.path.join(bin_dir(root), "lib"))
    for name, src in sources:
        if os.path.realpath(src).startswith(lib + os.sep):
            raise ResearchError(
                "`.research/bin/research` cannot upgrade itself: it is the copy being replaced.",
                hint="Run it from an installed Research OS instead — `research bin install --force` with "
                     "the pip-installed CLI, or let the VS Code extension refresh it (it does this on "
                     "open). `research bin install --force` from the project's own Research OS also refreshes it.")
    _ = lib
    bdir = bin_dir(root)
    lib = os.path.join(bdir, "lib")
    stamp = _stamp(sources, python)
    stamp_file = os.path.join(lib, ".stamp")
    posix, win = os.path.join(bdir, "research"), os.path.join(bdir, "research.cmd")
    current = os.path.exists(stamp_file) and open(stamp_file).read().strip() == stamp
    if current and os.path.exists(posix) and open(posix).read() != _posix_launcher(python):
        current = False     # same code, new launcher template
    _ensure_gitignored(root)
    if current and not force and os.path.exists(posix) and os.path.exists(win):
        return {"path": launcher(root), "updated": False, "stamp": stamp, "link": _try_link(root)}
    os.makedirs(bdir, exist_ok=True)
    tmp = lib + ".tmp"
    shutil.rmtree(tmp, ignore_errors=True)
    for name, src in sources:
        for f in _walk(src):
            dst = os.path.join(tmp, name, os.path.relpath(f, src))
            os.makedirs(os.path.dirname(dst), exist_ok=True)
            shutil.copy2(f, dst)
    with open(os.path.join(tmp, ".stamp"), "w") as f:
        f.write(stamp + "\n")
    old = lib + ".old"
    shutil.rmtree(old, ignore_errors=True)
    if os.path.exists(lib):
        os.replace(lib, old)
    os.replace(tmp, lib)
    shutil.rmtree(old, ignore_errors=True)
    with open(posix, "w", newline="\n") as f:
        f.write(_posix_launcher(python))
    os.chmod(posix, 0o755)
    with open(win, "w", newline="") as f:
        f.write(_windows_launcher(python))
    return {"path": launcher(root), "updated": True, "stamp": stamp, "link": _try_link(root)}


# ----------------------------------------------------------------------------------------------- `./research` in the main checkout
def _git(cwd: str, *args: str) -> Optional[str]:
    import subprocess
    r = subprocess.run(["git", *args], cwd=cwd, capture_output=True, text=True)
    return r.stdout.strip() if r.returncode == 0 else None


def _primary_checkout(root: str) -> Optional[str]:
    """The repository's main checkout (not a linked experiment worktree), where a link is useful. None if `root` is not one."""
    top = _git(root, "rev-parse", "--show-toplevel")
    gd, cd = _git(root, "rev-parse", "--absolute-git-dir"), _git(root, "rev-parse", "--path-format=absolute", "--git-common-dir")
    return top if top and gd and cd and os.path.realpath(gd) == os.path.realpath(cd) else None


def link(root: str, name: str = "research") -> Optional[Dict[str, Any]]:
    """`<main checkout>/research` -> the project launcher, so `./research …` works from main without a long path or PATH change.
    Local only: the link is added to .git/info/exclude (never committed), absolute (machine-specific) and never replaces an existing
    file or directory. Returns None when `root` is not the main checkout or the launcher does not exist."""
    top, target = _primary_checkout(root), launcher(root)
    if not top or not os.path.exists(target) or os.name == "nt":
        return None
    dest = os.path.join(top, name)
    if os.path.islink(dest):
        if os.path.realpath(dest) == os.path.realpath(target):
            _exclude(top, name)
            return {"path": dest, "target": target, "created": False}
        os.remove(dest)          # our own stale link (project moved or ledger re-linked)
    elif os.path.lexists(dest):
        raise ResearchError(f"{dest} already exists and is not a Research OS link; nothing was changed.",
                            hint=f"Pick another name: `research bin link --name rs`.")
    os.symlink(target, dest)
    _exclude(top, name)
    return {"path": dest, "target": target, "created": True}


def _try_link(root: str) -> Optional[Dict[str, Any]]:
    """Installing the launcher must never fail because of the convenience link (a name clash, a read-only checkout)."""
    try:
        return link(root)
    except (ResearchError, OSError) as ex:
        return {"path": None, "target": None, "created": False, "error": str(ex)}


def unlink(root: str, name: str = "research") -> Dict[str, Any]:
    top = _primary_checkout(root)
    dest = os.path.join(top, name) if top else None
    if dest and os.path.islink(dest) and os.path.realpath(dest) == os.path.realpath(launcher(root)):
        os.remove(dest)
        return {"path": dest, "removed": True}
    return {"path": dest, "removed": False}


def _exclude(top: str, name: str) -> None:
    path = _git(top, "rev-parse", "--path-format=absolute", "--git-path", "info/exclude")
    if not path:
        return
    entry = "/" + name
    try:
        text = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if entry in text.splitlines():
            return
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "a", encoding="utf-8") as f:
            f.write(("" if not text or text.endswith("\n") else "\n") + "# Research OS: local link to the project CLI\n" + entry + "\n")
    except OSError:
        pass
